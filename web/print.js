function postApprovalSections(otherDetails, assignment, events, wrapped) {
  const context = document.createElement('canvas').getContext('2d');
  const family = wrapped ? serif : sans;
  context.font = '10px ' + family;
  const split = Boolean(assignment && !wrapped);
  const divider = formWidth * .55;
  const separatorColor = '#b7c0ba';
  const left = { x: 2, end: split ? divider - 8 : formWidth - 2, entries: [], start: 0 };
  const right = { x: divider + 8, end: formWidth - 2, entries: [], start: 0 };
  const columns = split ? [left, right] : [left];
  function heading(label) {
    left.entries.push({ line: label, heading: true });
  }
  function detail(text, timeline = false) {
    const width = left.end - left.x - (timeline ? 12 : 0);
    left.entries.push(...wrapText(context, text, width).map(line => ({ line, timeline })));
  }
  for (const [label, value] of otherDetails) {
    heading(label);
    detail(value);
  }
  heading('Request timeline');
  for (const event of events) {
    const note = event.note?.trim();
    const entry = { line: eventTitle(event), heading: true, timeline: true, marker: true };
    const metadata = approvalTime(event.occurred_at) + ' PHT · ' + event.actor_name;
    if (wrapped) {
      context.font = '9.5px ' + family;
      const metadataX = left.end - context.measureText(metadata).width;
      context.font = 'bold 10px ' + family;
      const titleEnd = left.x + 12 + context.measureText(entry.line).width;
      if (metadataX >= titleEnd + 12) Object.assign(entry, { metadata, metadataX });
      context.font = '10px ' + family;
    }
    left.entries.push(entry);
    if (!entry.metadata) detail(metadata, true);
    if (note) detail(note, true);
    for (const { label, from, to } of correctionHistory(event)) {
      detail(label + '\nFrom  ' + from + '\nTo  ' + to, true);
    }
  }

  if (split) {
    right.entries.push({ line: 'Detailed work assignment', heading: true });
    const enteredLines = assignment.split(/\r\n?|\n/).filter(line => line.trim());
    const indent = enteredLines.length > 1 ? 12 : 0;
    for (const enteredLine of enteredLines) {
      const lines = wrapText(context, enteredLine, right.end - right.x - indent);
      right.entries.push(...lines.map((line, index) => ({ line, indent, bullet: indent > 0 && index === 0 })));
    }
  }
  const stamp = {};
  if (!wrapped) (split ? right : left).entries.push({ stamp: true });
  const sections = [];
  const pageRows = 22;
  while (columns.some(column => column.start < column.entries.length)) {
    const chunks = columns.map(column => {
      const { start, entries } = column;
      let end = Math.min(start + pageRows, entries.length);
      if (end < entries.length && (entries[end]?.stamp || entries[end - 1]?.heading)) end--;
      column.start = end;
      return { ...column, notes: entries.slice(start, end) };
    });
    sections.push(formSection(context, 'Details after approval', ({ add, text }) => {
      const height = 10 + 12 * Math.max(...chunks.map(({ notes }) => notes.length + (split && notes.at(-1)?.stamp ? 1 : 0)));
      if (split && chunks[1].notes.length) {
        add('line', { x1: divider, x2: divider, y1: 2, y2: height - 5, stroke: separatorColor, 'stroke-width': .7 });
      }
      for (const { x, end, notes } of chunks) {
        const first = notes.findIndex(entry => entry.timeline);
        const last = notes.findLastIndex(entry => entry.timeline);
        if (first >= 0) add('line', { x1: x + 3, x2: x + 3, y1: 8 + first * 12, y2: 12 + last * 12, stroke: separatorColor, 'stroke-width': .7 });
        for (const [index, entry] of notes.entries()) {
          const y = 12 + index * 12;
          if (entry.stamp) {
            Object.assign(stamp, { node: add('g', { 'data-print-stamp': '' }), x, y, width: end - x });
            continue;
          }
          const { line, heading: bold, timeline, marker, indent = 0, bullet } = entry;
          if (marker) add('circle', { cx: x + 3, cy: y - 3, r: 2.4, fill: '#235544' });
          if (bullet) add('circle', { cx: x + 3, cy: y - 3, r: 1.7, fill: '#111' });
          text(line, x + (timeline ? 12 : indent), y, timeline && !bold ? 9.5 : 10,
            bold ? 'bold' : 'normal', timeline && !bold ? '#444' : '#111');
          if (entry.metadata) text(entry.metadata, entry.metadataX, y, 9.5, 'normal', '#444');
        }
      }
      return height;
    }, family));
  }
  return { sections, stamp };
}

function paginatePrint(sections, footer, paperWidth, paperHeight) {
  const root = document.getElementById('print-root');
  const contentWidth = (paperWidth - 2 * printInset) * pxPerMm;
  const limit = (paperHeight - 2 * printInset - 1.5) * pxPerMm;
  const measure = document.createElement('div');
  measure.className = 'print-measure';
  measure.style.width = contentWidth + 'px';
  measure.append(footer);
  document.body.append(measure);
  const footerHeight = footer.getBoundingClientRect().height;
  measure.remove();

  const fullHeight = sections.reduce((sum, section) => sum + section.height, 0) * contentWidth / formWidth;
  const proposed = (limit - footerHeight) / fullHeight;
  // Fit modest overflow on one sheet while keeping the smallest text legible.
  const scale = proposed >= .88 && proposed < 1 ? proposed : 1;
  const ratio = contentWidth * scale / formWidth;
  const pages = [];
  let sheet, used, indices;
  const pageSections = [];
  function newSheet() {
    sheet = document.createElement('div');
    sheet.className = 'print-sheet';
    used = 0;
    indices = [];
    pages.push(sheet);
    pageSections.push(indices);
  }
  newSheet();
  for (const [index, { svg, height }] of sections.entries()) {
    const itemHeight = height * ratio;
    const last = index === sections.length - 1;
    const groupHeight = itemHeight + (last && itemHeight + footerHeight <= limit ? footerHeight : 0);
    if (used && used + groupHeight > limit + .01) newSheet();
    if (scale < 1) svg.style.width = scale * 100 + '%';
    sheet.append(svg);
    indices.push(index);
    used += itemHeight;
  }
  if (used + footerHeight > limit + .01) newSheet();
  sheet.append(footer);
  root.replaceChildren(...pages);
  return { scale, pageSections };
}

export async function preparePrint(row, paper, events, template = 'original') {
  const paperWidth = paper === 'Letter' ? 215.9 : 210;
  const paperHeight = paper === 'Letter' ? 279.4 : 297;
  const wrapped = template === 'wrapped';
  const family = wrapped ? serif : sans;
  const fontCss = wrapped ? await loadSerifFonts() : '';
  const { sections, otherDetails } = await (wrapped ? wrappedForm(row) : originalForm(row));
  const details = postApprovalSections(otherDetails, row.form.assignment_remarks, events, wrapped);
  sections.push(...details.sections);
  for (const section of sections) section.fontCss = fontCss;
  document.getElementById('print-preview').style.setProperty('--paper-width', paperWidth + 'mm');
  let rules = document.getElementById('print-paper');
  if (!rules) {
    rules = document.createElement('style');
    rules.id = 'print-paper';
    document.head.append(rules);
  }
  // Each sheet supplies its own inset even if the browser's margins are disabled.
  rules.textContent = '@page { size: ' + (paper === 'Letter' ? 'Letter' : 'A4') + ' portrait; margin: 0; }';
  const root = document.getElementById('print-root');
  root.style.setProperty('--print-inset', printInset + 'mm');
  root.style.setProperty('--print-paper-height', paperHeight + 'mm');
  const footer = document.createElement('footer');
  footer.className = 'print-footer';
  footer.style.fontFamily = family;
  footer.textContent = noticeText;
  if (wrapped) {
    details.stamp.node = document.createElement('span');
    details.stamp.node.className = 'print-footer-stamp';
    details.stamp.footer = true;
    footer.append(details.stamp.node);
  }

  const prepared = { sections, stamp: details.stamp, paperWidth, paperHeight, family };
  stampPrint(prepared, 'Prepared for print');
  return { ...prepared, ...paginatePrint(sections, footer, paperWidth, paperHeight) };
}

function printStampText(action) {
  return action + ' · ' + approvalTime(new Date()) + ' PHT';
}

function stampLines(context, action, width, family, scale = 1) {
  context.font = 9 * scale + 'px ' + family;
  return wrapText(context, printStampText(action), width * scale);
}

export function stampPrint({ stamp, family }, action = 'Printed') {
  if (stamp.footer) {
    stamp.node.textContent = printStampText(action);
    return;
  }
  const context = document.createElement('canvas').getContext('2d');
  stamp.node.replaceChildren(...stampLines(context, action, stamp.width, family).map((line, index) => {
    const node = svgNode('text', { x: stamp.x, y: stamp.y + index * 11, 'font-family': family, 'font-size': 9, fill: '#444' });
    node.textContent = line;
    return node;
  }));
}

export function preparePrintImage(sections) {
  return Promise.all(sections.map(async ({ svg, height, fontCss }) => {
    const copy = svg.cloneNode(true);
    copy.removeAttribute('style');
    copy.querySelector('[data-print-stamp]')?.remove();
    copy.setAttribute('width', formWidth);
    copy.setAttribute('height', height);
    if (fontCss) {
      const style = svgNode('style', {});
      style.textContent = fontCss;
      copy.prepend(style);
    }
    const layer = new Image();
    layer.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(new XMLSerializer().serializeToString(copy));
    await layer.decode();
    return layer;
  }));
}

export function drawPrintImage({ sections, stamp, paperWidth, paperHeight, family, scale: fit }, layers, action,
  indices = sections.map((_, index) => index), includeFooter = true) {
  const canvas = document.createElement('canvas');
  const context = canvas.getContext('2d');
  const pageWidth = paperWidth * pxPerMm;
  const inset = printInset * pxPerMm;
  const contentWidth = pageWidth - 2 * inset;
  const sectionWidth = contentWidth * fit;
  const sectionScale = sectionWidth / formWidth;
  const sectionStart = (pageWidth - sectionWidth) / 2;
  const contentEnd = inset + indices.reduce((sum, index) => sum + sections[index].height * sectionScale, 0);
  context.font = '12px ' + family;
  const footerLines = includeFooter ? wrapText(context, noticeText, contentWidth) : [];
  const footerHeight = includeFooter ? 8 + footerLines.length * 16 + (stamp.footer ? 18 : 0) : 0;
  const imageHeight = Math.max(paperHeight * pxPerMm, contentEnd + footerHeight + inset);
  const scale = Math.min(2.5, Math.sqrt(12_000_000 / (pageWidth * imageHeight)), 8192 / imageHeight);
  canvas.width = Math.round(pageWidth * scale);
  canvas.height = Math.round(imageHeight * scale);
  context.scale(scale, scale);
  context.fillStyle = '#fff';
  context.fillRect(0, 0, canvas.width / scale, canvas.height / scale);

  let sectionTop = inset;
  for (const index of indices) {
    const { svg, height: units } = sections[index];
    const height = units * sectionScale;
    context.drawImage(layers[index], sectionStart, sectionTop, sectionWidth, height);
    if (svg.contains(stamp.node)) {
      context.fillStyle = '#444';
      context.textBaseline = 'alphabetic';
      for (const [row, line] of stampLines(context, action, stamp.width, family, sectionScale).entries()) {
        context.fillText(line, sectionStart + stamp.x * sectionScale, sectionTop + (stamp.y + row * 11) * sectionScale);
      }
    }
    sectionTop += height;
  }

  if (!includeFooter) return canvas;
  const footerTop = imageHeight - inset - footerHeight;
  context.strokeStyle = '#caa6ab';
  context.beginPath();
  context.moveTo(inset, footerTop);
  context.lineTo(pageWidth - inset, footerTop);
  context.stroke();
  context.fillStyle = noticeColor;
  context.font = '12px ' + family;
  context.textBaseline = 'top';
  for (const [row, line] of footerLines.entries()) context.fillText(line, inset, footerTop + 8 + row * 16);
  if (stamp.footer) {
    context.fillStyle = '#444';
    context.font = '10.67px ' + family;
    context.fillText(printStampText(action), inset, footerTop + 12 + footerLines.length * 16);
  }
  return canvas;
}
